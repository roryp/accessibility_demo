// Lab 3: HydraFusion performs a read-only WCAG 2.2 audit ("testing") of the site through the Copilot SDK.
//   npm run audit
//   npm run audit -- --budget 40             (hard cap: 40 AI credits = $0.40; runtime minimum is 30)
//   npm run audit -- --soft-budget 1         (app-side cap: abort as soon as 1 credit = $0.01 is spent)
//   npm run audit -- --model claude-opus-5   (stretch: compare with a single model)
import fs from "node:fs";
import path from "node:path";
import { runHydraFusionTask, parseRunArgs } from "./lib/hydrafusion.mjs";
import { recordRun, newRunId, fmtCredits, fmtUsd } from "./lib/cost-tracker.mjs";
import { INSTRUCTIONS, AUDIT_PROMPT } from "./lib/prompts.mjs";
import { REPORTS_DIR, ensureSite, rel } from "./lib/paths.mjs";

const { budget, softBudget, model } = parseRunArgs({ defaultBudget: 50 });
ensureSite();
const startedAt = new Date();
const run = newRunId("audit");
const who = model === "hydrafusion" ? "HydraFusion" : model;

console.log(`\n=== Lab 3 · ${who} accessibility audit (read-only) ===`);
const result = await runHydraFusionTask({
  run,
  prompt: AUDIT_PROMPT,
  instructions: INSTRUCTIONS,
  writableDirs: [],
  budgetCredits: budget,
  softBudgetCredits: softBudget,
  model,
});

recordRun(result.tracker, {
  script: "audit",
  model,
  startedAt: startedAt.toISOString(),
  endedAt: new Date().toISOString(),
  outcome: result.outcome,
  settled: result.settled,
  reconciliation: result.reconciliation,
  budgetExhausted: result.budgetExhausted,
  softBudgetStopped: result.softBudgetStopped,
  error: result.error?.message ?? null,
});

const total = result.tracker.totalNanoAiu;
const routes = result.tracker.routes.map((r) => `${r.pattern} (primary ${r.primaryModel}${r.secondaryModel ? `, reviewer ${r.secondaryModel}` : ""})`);
const report = [
  `# WCAG 2.2 audit: Bean & Bloom Café`,
  ``,
  `_Generated by ${who} through the GitHub Copilot SDK on ${startedAt.toISOString()}._`,
  routes.length ? `_HydraFusion execution pattern: ${routes.join("; ")}._` : "",
  ``,
  result.reply ?? `_No report was produced (outcome: ${result.outcome}${result.error ? `, ${result.error.message}` : ""})._`,
  ``,
  `---`,
  `**Cost of this audit:** ${fmtCredits(total)} = **${fmtUsd(total)}** across ${result.tracker.calls.length} model calls.`,
].join("\n");

fs.mkdirSync(REPORTS_DIR, { recursive: true });
const out = path.join(REPORTS_DIR, "audit-report.md");
fs.writeFileSync(out, report);

console.log(`\n📄 Audit report: ${rel(out)}`);
console.log(`📒 Cost ledger: reports/usage-ledger.jsonl · run summary: reports/runs.jsonl · raw events: reports/events/${run}.jsonl  (all runs: npm run cost)\n`);
if (!result.reply) process.exitCode = 1;
